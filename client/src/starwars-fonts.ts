// ─── Font selection ──────────────────────────────────────────────────────────

export type FontSize = 5 | 7 | 8 | 10 | 14 | 16 | 20 | 24 | 32 | 40 | 42;

export function snapHeight(h: number): FontSize {
  if (h <= 6) return 5;
  if (h <= 7) return 7;
  if (h <= 9) return 8;
  if (h <= 12) return 10;
  if (h <= 15) return 14;
  if (h <= 18) return 16;
  if (h <= 22) return 20;
  if (h <= 28) return 24;
  if (h <= 36) return 32;
  if (h <= 41) return 40;
  return 42;
}

export function getFontConfig(size: FontSize): {
  map: FontMap;
  fontWidth: number;
  fontHeight: number;
} {
  switch (size) {
    case 5:  return { map: font5,  fontWidth: 3,  fontHeight: 5  };
    case 7:  return { map: font7,  fontWidth: 4,  fontHeight: 7  };
    case 8:  return { map: font8,  fontWidth: 5,  fontHeight: 8  };
    case 10: return { map: font10, fontWidth: 6,  fontHeight: 10 };
    case 14: return { map: font14, fontWidth: 8,  fontHeight: 14 };
    case 16: return { map: font16, fontWidth: 10, fontHeight: 16 };
    case 20: return { map: font20, fontWidth: 12, fontHeight: 20 };
    case 24: return { map: font24, fontWidth: 15, fontHeight: 24 };
    case 32: return { map: font32, fontWidth: 20, fontHeight: 32 };
    case 40: return { map: font40, fontWidth: 25, fontHeight: 40 };
    case 42: return { map: font42, fontWidth: 24, fontHeight: 42 };
  }
}
